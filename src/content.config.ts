import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';
import { TOPIC_IDS } from './data/topics.mjs';

// One collection for every kind of project. Files live in
//   src/content/projects/<section>/<year>/<slug>.md
// and the entry id is the slug, so URLs are /<section>/<slug>/.
const projects = defineCollection({
  loader: glob({
    pattern: '**/*.md',
    base: './src/content/projects',
    generateId: ({ entry }) => entry.split('/').pop()!.replace(/\.md$/, ''),
  }),
  schema: z.object({
    // Identity
    type: z.enum(['report', 'dashboard', 'project']),
    // pdf: landing page + embedded PDF; digital: full web-native report body
    format: z.enum(['pdf', 'digital']).default('digital'),
    number: z.string().regex(/^\d{4}-\d{3,}$/, 'Use YYYY-NNN, e.g. 2026-001'),
    title: z.string(),
    subtitle: z.string().optional(),
    series: z.string().optional(),

    // Indexing metadata
    description: z.string().max(320, 'Keep the meta description under 320 characters'),
    abstract: z.string().optional(),
    topics: z.array(z.enum(TOPIC_IDS as [string, ...string[]])).min(1),
    keywords: z.array(z.string()).default([]),
    regions: z.array(z.string()).default([]),
    language: z.string().default('en'),
    license: z.string().optional(),
    doi: z.string().optional(),

    // People & dates
    authors: z
      .array(z.object({ name: z.string(), role: z.string().optional(), url: z.string().url().optional() }))
      .default([{ name: 'Hunter Hughes', role: 'Founder & CEO, H Heuristics' }]),
    date: z.coerce.date(),
    updated: z.coerce.date().optional(),

    // Assets (paths relative to site root, usually /<section>/<slug>/...)
    cover: z.string().optional(),
    coverAlt: z.string().optional(),
    pdf: z.string().optional(),
    pages: z.number().int().optional(),
    embed: z.string().optional(), // dashboards: URL of the interactive app
    externalUrl: z.string().url().optional(),

    // Report structure (generated by scripts/ingest.mjs)
    chapters: z.array(z.object({ id: z.string(), number: z.string().optional(), title: z.string(), page: z.number().int().optional() })).default([]),
    highlights: z.array(z.string()).default([]),
    stats: z
      .object({
        words: z.number().int(),
        readingMinutes: z.number().int(),
        figures: z.number().int().default(0),
        tables: z.number().int().default(0),
        references: z.number().int().default(0),
      })
      .optional(),

    // Publishing state
    status: z.enum(['published', 'experimental', 'archived']).default('published'),
    featured: z.boolean().default(false),
    draft: z.boolean().default(false),
  }),
});

export const collections = { projects };
